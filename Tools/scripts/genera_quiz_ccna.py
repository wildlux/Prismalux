def crea_db(path: pathlib.Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path))
    c = conn.cursor()
    c.execute("PRAGMA journal_mode=WAL")
    c.execute("""
        CREATE TABLE IF NOT EXISTS questions (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            domanda     TEXT NOT NULL,
            r0          TEXT,
            r1          TEXT,
            r2          TEXT,
            r3          TEXT,
            corretta    INTEGER DEFAULT 0,
            spiegazione TEXT,
            tema        TEXT
        )
    """)
    c.execute("SELECT COUNT(*) FROM questions")
    esistenti = c.fetchone()[0]
    if esistenti > 0:
        print(f"[info] DB esistente con {esistenti} domande. Aggiorno...")
        c.execute("DELETE FROM questions")

    c.executemany(
        "INSERT INTO questions (domanda,r0,r1,r2,r3,corretta,spiegazione,tema) "
        "VALUES (?,?,?,?,?,?,?,?)",
        QUESTIONS
    )
    conn.commit()
    n = conn.execute("SELECT COUNT(*) FROM questions").fetchone()[0]
    conn.close()
    print(f"[OK] Scritte {n} domande in {path}")


